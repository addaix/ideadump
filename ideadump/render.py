"""Markdown views of the records: one ``README.md`` per idea and an index at the root.

The records (``idea.json``) are the source of truth; these pages are regenerated from
them on every write, so a person browsing the store on GitHub (or a phone) sees each
idea's folder open on its page, and the root opens on the index.
"""

from __future__ import annotations

import re
from collections import defaultdict
from collections.abc import Iterable
from datetime import datetime, timezone

from ideadump.base import IDEAS_DIR, README_FILE

__all__ = ["idea_page", "index_page", "research_depth", "created_at"]


def research_depth(record: dict) -> str:
    """How far an idea has been researched: ``deep``, ``light`` or ``-``."""
    depths = {note.get("depth") for note in record.get("research", [])}
    return "deep" if "deep" in depths else "light" if depths else "-"


def created_at(record: dict) -> datetime:
    """When an idea was captured, comparable across machines in different time zones.

    >>> a = {"created": "2026-11-14T23:30:00+01:00"}
    >>> b = {"created": "2026-11-14T22:45:00+00:00"}
    >>> created_at(a) < created_at(b)
    True
    """
    try:
        moment = datetime.fromisoformat(record.get("created", ""))
    except ValueError:
        return datetime.min.replace(tzinfo=timezone.utc)
    return moment if moment.tzinfo else moment.replace(tzinfo=timezone.utc)


def _text(value: str) -> str:
    """A title safe inside a Markdown table cell and link label."""
    return re.sub(r"([|\[\]])", r"\\\1", value.replace("\n", " "))


def _tags(record: dict) -> str:
    return ", ".join(f"`{t}`" for t in record.get("tags", [])) or "-"


def idea_page(record: dict, *, titles: dict[str, str] | None = None) -> str:
    """The page of one idea: the owner's words, the summary, research and links.

    >>> page = idea_page({"id": "x", "title": "T", "words": "w", "created": "2026-11-14"})
    >>> page.splitlines()[0]
    '# T'
    """
    titles = titles or {}
    lines = [
        f"# {record['title']}",
        "",
        f"`{record['id']}` · {record.get('status', 'new')} · captured {record.get('created', '')[:10]}"
        + (f" from {record['source']}" if record.get("source") else "")
        + f" · research: {research_depth(record)}",
        "",
        f"Tags: {_tags(record)}",
        "",
    ]
    if record.get("summary"):
        lines += ["## Summary", "", record["summary"].strip(), ""]
    lines += ["## In the owner's words", ""]
    lines += [
        f"> {line}" if line else ">" for line in record["words"].strip().splitlines()
    ]
    lines.append("")
    if record.get("research"):
        lines += ["## Research", ""]
        for note in record["research"]:
            lines.append(
                f"- [{note.get('title') or note['file']}]({note['file']}) ({note['depth']}, {note['date'][:10]})"
            )
        lines.append("")
    if record.get("links"):
        lines += ["## Related ideas", ""]
        for link in record["links"]:
            other = link["id"]
            label = titles.get(other, other)
            why = f": {link['why']}" if link.get("why") else ""
            lines.append(f"- [{_text(label)}](../{other}/{README_FILE}){why}")
        lines.append("")
    return "\n".join(lines)


def index_page(records: Iterable[dict]) -> str:
    """The root index: every idea, newest first, then the ideas under each tag.

    >>> print(index_page([]).splitlines()[0])
    # Ideas
    """
    records = sorted(records, key=created_at, reverse=True)

    def link(r):
        return f"[{_text(r['title'])}]({IDEAS_DIR}/{r['id']}/{README_FILE})"

    lines = [
        "# Ideas",
        "",
        f"{len(records)} ideas. Generated by ideadump from the `idea.json` records; do not edit by hand.",
        "",
        "| Captured | Idea | Status | Research | Tags |",
        "|---|---|---|---|---|",
    ]
    for r in records:
        lines.append(
            f"| {r.get('created', '')[:10]} | {link(r)} | {r.get('status', 'new')} | {research_depth(r)} | {_tags(r)} |"
        )
    by_tag = defaultdict(list)
    for r in records:
        for tag in r.get("tags", []):
            by_tag[tag].append(r)
    if by_tag:
        lines += ["", "## By tag", ""]
        for tag in sorted(by_tag):
            lines.append(f"- **{tag}**: " + ", ".join(link(r) for r in by_tag[tag]))
    lines.append("")
    return "\n".join(lines)
